#ifndef GLASSTESTS_H
#define GLASSTESTS_H

#include <QString>
#include <QStringList>
#include <QVector>
#include <QDateTime>
#include "restaurantmanager.h"
#include "xlsxwriter.h"

// Результат одного теста
struct TestResult {
    QString name;
    QString expected;
    QString actual;
    bool    passed;
};

class GlassBoxTests {
private:
    QVector<TestResult> results;

    // Запускает один тест и сохраняет результат
    void check(const QString &name, const QString &expected, const QString &actual) {
        results.append({ name, expected, actual, expected == actual });
    }

public:
    void runAll() {
        results.clear();

        // ================================================================
        // ТЕСТ 1: Добавить блюдо "Борщ" в меню
        // Ожидаем: в меню стало 1 блюдо
        // ================================================================
        {
            RestaurantManager m;
            m.addDish(Dish("Борщ", "Супы", 5.50));
            check("Добавить блюдо Борщ в пустое меню — в меню 1 блюдо",
                  "1",
                  QString::number(m.getDishes().size()));
        }

        // ================================================================
        // ТЕСТ 2: Добавить два блюда — в меню должно быть 2 блюда
        // ================================================================
        {
            RestaurantManager m;
            m.addDish(Dish("Борщ",  "Супы",          5.50));
            m.addDish(Dish("Стейк", "Горячие блюда", 18.00));
            check("Добавить Борщ и Стейк — в меню 2 блюда",
                  "2",
                  QString::number(m.getDishes().size()));
        }

        // ================================================================
        // ТЕСТ 3: Удалить одно блюдо из двух — в меню должно остаться 1
        // ================================================================
        {
            RestaurantManager m;
            m.addDish(Dish("Борщ",  "Супы",          5.50));
            m.addDish(Dish("Стейк", "Горячие блюда", 18.00));
            m.removeDish(0); // удаляем Борщ
            check("Удалить Борщ из меню из 2 блюд — остаётся 1 блюдо",
                  "1",
                  QString::number(m.getDishes().size()));
        }

        // ================================================================
        // ТЕСТ 4: Изменить название блюда Борщ на Солянка
        // Ожидаем: в меню блюдо называется Солянка
        // ================================================================
        {
            RestaurantManager m;
            m.addDish(Dish("Борщ", "Супы", 5.50));
            m.updateDish(0, Dish("Солянка", "Супы", 6.00));
            check("Переименовать блюдо Борщ в Солянку — название Солянка",
                  "Солянка",
                  m.getDishes()[0].getName());
        }

        // ================================================================
        // ТЕСТ 5: Изменить цену блюда Борщ с 5.50 на 7.00
        // Ожидаем: цена блюда стала 7.00
        // ================================================================
        {
            RestaurantManager m;
            m.addDish(Dish("Борщ", "Супы", 5.50));
            m.updateDish(0, Dish("Борщ", "Супы", 7.00));
            check("Изменить цену Борща с 5.50 на 7.00 — цена 7.00",
                  "7.00",
                  QString::number(m.getDishes()[0].getPrice(), 'f', 2));
        }

        // ================================================================
        // ТЕСТ 6: Сортировка блюд по цене — самое дешёвое встаёт первым
        // Добавляем: Стейк 18.00, Борщ 5.50, Тирамису 7.00
        // После сортировки первое блюдо — Борщ (5.50)
        // ================================================================
        {
            RestaurantManager m;
            m.addDish(Dish("Стейк",    "Горячие блюда", 18.00));
            m.addDish(Dish("Борщ",     "Супы",           5.50));
            m.addDish(Dish("Тирамису", "Десерты",         7.00));
            m.sortDishesByPrice();
            check("Сортировка меню по цене — первым стоит Борщ (5.50)",
                  "Борщ",
                  m.getDishes()[0].getName());
        }

        // ================================================================
        // ТЕСТ 7: Сумма заказа №1
        // Заказ №1: Борщ x2 (5.50 x 2 = 11.00) + Стейк x1 (18.00 x 1 = 18.00)
        // Итого = 29.00
        // ================================================================
        {
            RestaurantManager m;
            m.addDish(Dish("Борщ",  "Супы",          5.50));
            m.addDish(Dish("Стейк", "Горячие блюда", 18.00));
            m.addOrder(Order(1, 3, "Борщ",  2));
            m.addOrder(Order(1, 3, "Стейк", 1));
            check("Заказ №1: Борщ x2 + Стейк x1 — сумма 29.00 руб.",
                  "29.00",
                  QString::number(m.orderTotal(1), 'f', 2));
        }

        // ================================================================
        // ТЕСТ 8: Сумма заказа №2
        // Заказ №2: Тирамису x3 (7.00 x 3 = 21.00) + Цезарь x1 (8.50 x 1 = 8.50)
        // Итого = 29.50
        // ================================================================
        {
            RestaurantManager m;
            m.addDish(Dish("Тирамису", "Десерты",          7.00));
            m.addDish(Dish("Цезарь",   "Холодные закуски", 8.50));
            m.addOrder(Order(2, 5, "Тирамису", 3));
            m.addOrder(Order(2, 5, "Цезарь",   1));
            check("Заказ №2: Тирамису x3 + Цезарь x1 — сумма 29.50 руб.",
                  "29.50",
                  QString::number(m.orderTotal(2), 'f', 2));
        }

        // ================================================================
        // ТЕСТ 9: Самый прибыльный заказ из трёх
        // Заказ №1 = 29.00, Заказ №2 = 29.50, Заказ №3 = 36.00
        // Самый прибыльный = №3
        // ================================================================
        {
            RestaurantManager m;
            m.addDish(Dish("Борщ",     "Супы",          5.50));
            m.addDish(Dish("Стейк",    "Горячие блюда", 18.00));
            m.addDish(Dish("Тирамису", "Десерты",        7.00));
            m.addDish(Dish("Цезарь",   "Холодные закуски",8.50));
            m.addDish(Dish("Пельмени", "Горячие блюда",  9.00));
            m.addOrder(Order(1, 3, "Борщ",     2));
            m.addOrder(Order(1, 3, "Стейк",    1));
            m.addOrder(Order(2, 5, "Тирамису", 3));
            m.addOrder(Order(2, 5, "Цезарь",   1));
            m.addOrder(Order(3, 1, "Пельмени", 4));
            check("Три заказа (29.00 / 29.50 / 36.00) — самый прибыльный №3",
                  "3",
                  QString::number(m.mostProfitableOrderNum()));
        }

        // ================================================================
        // ТЕСТ 10: Самое популярное блюдо в категории Горячие блюда
        // Стейк заказали 1 раз, Пельмени — 4 раза → популярнее Пельмени
        // ================================================================
        {
            RestaurantManager m;
            m.addDish(Dish("Стейк",    "Горячие блюда", 18.00));
            m.addDish(Dish("Пельмени", "Горячие блюда",  9.00));
            m.addOrder(Order(1, 2, "Стейк",    1));
            m.addOrder(Order(2, 1, "Пельмени", 4));
            check("В категории Горячие блюда: Стейк x1, Пельмени x4 — популярнее Пельмени",
                  "Пельмени",
                  m.mostPopularDishInCategory("Горячие блюда"));
        }

        // ================================================================
        // ТЕСТ 11: Самое популярное блюдо в категории Десерты
        // Тирамису заказали 3 раза, Чизкейк — 1 раз → популярнее Тирамису
        // ================================================================
        {
            RestaurantManager m;
            m.addDish(Dish("Тирамису", "Десерты", 7.00));
            m.addDish(Dish("Чизкейк",  "Десерты", 6.50));
            m.addOrder(Order(1, 4, "Тирамису", 3));
            m.addOrder(Order(2, 4, "Чизкейк",  1));
            check("В категории Десерты: Тирамису x3, Чизкейк x1 — популярнее Тирамису",
                  "Тирамису",
                  m.mostPopularDishInCategory("Десерты"));
        }

        // ================================================================
        // ТЕСТ 12: Заказы по убыванию суммы — на первом месте самый дорогой
        // Заказ №1 = 11.00, Заказ №2 = 36.00
        // После сортировки первым идёт Заказ №2
        // ================================================================
        {
            RestaurantManager m;
            m.addDish(Dish("Борщ",     "Супы",          5.50));
            m.addDish(Dish("Пельмени", "Горячие блюда", 9.00));
            m.addOrder(Order(1, 2, "Борщ",     2)); // 11.00
            m.addOrder(Order(2, 1, "Пельмени", 4)); // 36.00
            auto sorted = m.ordersSortedByTotal();
            check("Заказ №1 (11.00) и №2 (36.00) — после сортировки первый №2",
                  "2",
                  QString::number(sorted[0].first));
        }

        // ================================================================
        // ТЕСТ 13: Добавить заказ и проверить, что количество заказов = 1
        // ================================================================
        {
            RestaurantManager m;
            m.addDish(Dish("Борщ", "Супы", 5.50));
            m.addOrder(Order(1, 3, "Борщ", 2));
            check("Добавить один заказ — в списке заказов 1 запись",
                  "1",
                  QString::number(m.getOrders().size()));
        }

        // ================================================================
        // ТЕСТ 14: Удалить заказ — список заказов должен стать пустым
        // ================================================================
        {
            RestaurantManager m;
            m.addDish(Dish("Борщ", "Супы", 5.50));
            m.addOrder(Order(1, 3, "Борщ", 2));
            m.removeOrder(0);
            check("Добавить заказ, затем удалить — список заказов пуст (0 записей)",
                  "0",
                  QString::number(m.getOrders().size()));
        }

        // ================================================================
        // ТЕСТ 15: Проверка валидации — цена блюда не может быть отрицательной
        // Попытка создать блюдо с ценой -5 должна вызвать исключение
        // ================================================================
        {
            bool gotException = false;
            try {
                Dish d;
                d.setPrice(-5.00); // должно бросить исключение
            } catch (...) {
                gotException = true;
            }
            check("Установить цену блюда -5.00 (недопустимо) — программа выдаёт ошибку",
                  "да, ошибка поймана",
                  gotException ? "да, ошибка поймана" : "нет, ошибка не поймана");
        }
    }

    // Сохранить результаты в Excel (.xlsx)
    void saveXlsx(const QString &path) const {
        XlsxWriter wb;

        // Лист 1: результаты тестов
        XlsxSheet &sh = wb.addSheet("Результаты тестов");
        sh.addHeaderRow({ "Тест", "Ожидаемый результат", "ok?" });

        int passed = 0;
        for (const TestResult &r : results) {
            if (r.passed) ++passed;
            int okStyle = r.passed ? 2 : 3; // 2=зелёный, 3=красный
            sh.addRow({
                { r.name,     0, false },
                { r.expected, 0, false },
                { r.passed ? QString("ok") : QString("fail"), okStyle, false }
            });
        }

        // Итоговая строка
        sh.addRow({
            { QString("ИТОГО: %1 из %2 тестов пройдено").arg(passed).arg(results.size()), 4, false },
            { "", 0, false },
            { "", 0, false }
        });

        // Лист 2: сводка
        XlsxSheet &sv = wb.addSheet("Сводка");
        sv.addHeaderRow({ "Показатель", "Значение" });
        sv.addRow({{ "Дата запуска",      0, false },
                   { QDateTime::currentDateTime().toString("dd.MM.yyyy  hh:mm:ss"), 0, false }});
        sv.addRow({{ "Всего тестов",      0, false },
                   { QString::number(results.size()), 0, false }});
        sv.addRow({{ "Пройдено (ok)",     2, false },
                   { QString::number(passed), 2, false }});
        sv.addRow({{ "Провалено (fail)",  3, false },
                   { QString::number(results.size() - passed), 3, false }});

        wb.save(path);
    }

    const QVector<TestResult> &getResults() const { return results; }
};

#endif // GLASSTESTS_H
